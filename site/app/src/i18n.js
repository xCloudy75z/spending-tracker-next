export const messages = Object.freeze({ en: Object.freeze(en), ar: Object.freeze(ar) });

export function t(locale, key, values = {}) {
  const catalog = messages[locale] || messages.en;
  const template = catalog[key] ?? messages.en[key] ?? key;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name) => (
    Object.hasOwn(values, name) ? String(values[name]) : match
  ));
}

export function formatMoney(locale, value) {
  return new Intl.NumberFormat(locale === 'ar' ? 'ar-AE' : 'en-AE', {
    style: 'currency',
    currency: 'AED',
    currencyDisplay: 'code',
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(Number(value) || 0);
}

export function formatDate(locale, isoDate, options = {}) {
  const [year, month, day] = String(isoDate).split('-').map(Number);
  const date = new Date(year, month - 1, day, 12, 0, 0);
  return new Intl.DateTimeFormat(locale === 'ar' ? 'ar-AE' : 'en-AE', {
    day: 'numeric',
    month: 'short',
    year: options.includeYear === false ? undefined : 'numeric',
  }).format(date);
}

export function setDocumentLocale(documentLike, locale) {
  const normalized = locale === 'ar' ? 'ar' : 'en';
  documentLike.documentElement.setAttribute('lang', normalized);
  documentLike.documentElement.setAttribute('dir', normalized === 'ar' ? 'rtl' : 'ltr');
}
